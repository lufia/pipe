func reverse(a []string) []string {
	b := make([]string, 0, len(a))
	for _, s := range slices.Backward(a) {
		b = append(b, s)
	}
	return b
}

func concat(a, b []string) []string {
	r := make([]string, len(a)+len(b))
	copy(r[:len(a)], a)
	copy(r[len(a):], b)
	return r
}

